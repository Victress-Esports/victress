import { compare } from "./rl-compare.mjs";
let failed = 0;
const check = (ok, n) => { console.log(`${ok ? "PASS" : "FAIL"} ${n}`); if (!ok) failed++; };
const P = (name, team, score = 0, goals = 0, assists = 0, saves = 0, shots = 0) => ({ name, team, score, goals, assists, saves, shots });
const mk = (hp, np, t = [1, 0], nt = t) => ({ header: { team0_score: t[0], team1_score: t[1], players: hp }, network: { team0_score: nt[0], team1_score: nt[1], players: np } });
check(compare(mk([P("a", 0, 100, 1), P("b", 1, 50)], [P("b", 1, 50), P("a", 0, 100, 1)])).pass, "identical scoreboards pass, order does not matter");
check(compare(mk([P("a", 0)], [{ name: "a", team: 0, score: null, goals: null, assists: null, saves: null, shots: null }], [0, 0])).pass, "missing network values count as zero");
let r = compare(mk([P("a", 0, 100, 2)], [P("a", 0, 100, 1)]));
check(!r.pass && r.causes.join() === "field_goals", "one wrong field fails with its name");
r = compare(mk([P("a", 0)], [P("a", 0)], [1, 0], [0, 0]));
check(!r.pass && r.causes.join() === "team_score", "team score difference fails");
r = compare(mk([P("a", 0), P("b", 1)], [P("a", 0)]));
check(!r.pass && r.causes.includes("player_count") && r.causes.includes("player_not_found"), "missing player fails");
r = compare(mk([P("a", 1)], [{ ...P("a", 1), team: null }]));
check(!r.pass && r.causes.join() === "team_unresolved", "a player with no team in the network data is a team_unresolved failure");
r = compare(mk([P("a", 1)], [P("a", 0)]));
check(!r.pass && r.causes.join() === "team_mismatch", "wrong team fails");
r = compare(mk([P("a", 0)], [P("a", 0), P("ghost", 1)]));
check(!r.pass && r.causes.includes("player_count"), "an extra network player fails");
check(compare({ error: "x" }).causes.join() === "parse_error", "parse error is a failure");
check(compare(mk([P("a", 0, 1), P("a", 1, 2)], [P("a", 1, 2), P("a", 0, 1)])).pass, "duplicate names are matched by team");
console.log(failed ? `\n${failed} FAILED` : "\nall passed"); process.exit(failed ? 1 : 0);
